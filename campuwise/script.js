let currentLang = localStorage.getItem('campuwise_lang') || 'tr';
let faqData = null;

// Initialize Lucide Icons
lucide.createIcons();

// Navbar blur on scroll
const navbar = document.getElementById('navbar');
window.addEventListener('scroll', () => {
    if (window.scrollY > 20) {
        navbar.classList.add('shadow-lg', 'shadow-brand-indigo/5');
        navbar.classList.replace('bg-obsidian/80', 'bg-obsidian/95');
    } else {
        navbar.classList.remove('shadow-lg', 'shadow-brand-indigo/5');
        navbar.classList.replace('bg-obsidian/95', 'bg-obsidian/80');
    }
});

// Intersection Observer for Fade-in animations
const observerOptions = {
    root: null,
    rootMargin: '0px',
    threshold: 0.1
};

const observer = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('is-visible');
            observer.unobserve(entry.target);
        }
    });
}, observerOptions);

document.querySelectorAll('.fade-in-section').forEach(section => {
    observer.observe(section);
});

// Language Switcher Function
function switchLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('campuwise_lang', lang);
    
    // Update active button classes
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Translate DOM elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            elem.textContent = translations[lang][key];
        }
    });

    // Re-render FAQ with new language
    renderFaq();
}

// Fetch and Render Dynamic FAQ
async function loadFaq() {
    try {
        const response = await fetch('./FAQ.json');
        faqData = await response.json();
        renderFaq();
    } catch (error) {
        console.error('Failed to load FAQ.json:', error);
    }
}

function renderFaq() {
    const faqContainer = document.getElementById('faq-container');
    if (!faqContainer || !faqData || !faqData[currentLang]) return;

    faqContainer.innerHTML = '';

    faqData[currentLang].forEach(item => {
        const accordion = document.createElement('div');
        accordion.className = 'glass-card rounded-2xl overflow-hidden faq-item';
        accordion.innerHTML = `
            <button class="w-full px-6 py-5 text-left flex justify-between items-center focus:outline-none" onclick="toggleFaq(this)">
                <span class="font-semibold text-white">${item.question}</span>
                <i data-lucide="chevron-down" class="w-5 h-5 text-slate-400 transition-transform duration-300"></i>
            </button>
            <div class="px-6 pb-5 hidden text-slate-400 text-sm faq-content leading-relaxed">
                ${item.answer}
            </div>
        `;
        faqContainer.appendChild(accordion);
    });

    lucide.createIcons();
}

// FAQ Accordion Toggle
function toggleFaq(button) {
    const content = button.nextElementSibling;
    const icon = button.querySelector('i');
    
    if (content.classList.contains('hidden')) {
        content.classList.remove('hidden');
        if (icon) icon.style.transform = 'rotate(180deg)';
        button.parentElement.classList.add('border-brand-indigo/30');
    } else {
        content.classList.add('hidden');
        if (icon) icon.style.transform = 'rotate(0deg)';
        button.parentElement.classList.remove('border-brand-indigo/30');
    }
}

// Interactive Mobile App Preview Tabs
function switchTab(tabId) {
    const tabs = ['duyurular', 'harita', 'ring', 'yemekhane'];
    
    tabs.forEach(id => {
        const btn = document.getElementById(`tab-${id}`);
        const view = document.getElementById(`view-${id}`);
        if (!btn || !view) return;

        const icon = btn.querySelector('i');
        const text = btn.querySelector('span');

        if (id === tabId) {
            btn.className = 'text-left px-6 py-4 rounded-xl font-semibold transition-all glass-card border-brand-indigo/50 bg-white/5';
            if (icon) icon.classList.add('text-brand-indigo');
            if (text) {
                text.classList.add('text-white');
                text.classList.remove('text-slate-400');
            }
            
            view.classList.remove('opacity-0', 'pointer-events-none');
            view.classList.add('opacity-100');
        } else {
            btn.className = 'text-left px-6 py-4 rounded-xl font-semibold transition-all hover:bg-white/5 border border-transparent text-slate-400';
            if (icon) icon.classList.remove('text-brand-indigo');
            if (text) {
                text.classList.remove('text-white');
                text.classList.add('text-slate-400');
            }
            
            view.classList.remove('opacity-100');
            view.classList.add('opacity-0', 'pointer-events-none');
        }
    });
}

// Modal Handlers
function openModal(modalId) {
    const modal = document.getElementById(modalId);
    if (modal) {
        modal.classList.remove('hidden');
        modal.classList.add('flex');
        document.body.style.overflow = 'hidden';
    }
}

function closeModal(modalId) {
    const modal = document.getElementById(modalId);
    if (modal) {
        modal.classList.add('hidden');
        modal.classList.remove('flex');
        document.body.style.overflow = 'auto';
    }
}

// Close modals on escape key press
document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
        ['modal-contact', 'modal-privacy', 'modal-terms'].forEach(id => closeModal(id));
    }
});

// Initialize page on DOM load
document.addEventListener('DOMContentLoaded', () => {
    switchLanguage(currentLang);
    loadFaq();
});
